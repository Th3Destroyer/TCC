"""Teste de navegação do Pages. Requer servidor HTTP e Playwright/Chromium.
Defina PAGES_TEST_URL para testar outro endereço. Não altera dados do Django.
"""
import os
import shutil
from playwright.sync_api import sync_playwright, expect

BASE=os.environ.get('PAGES_TEST_URL', 'http://127.0.0.1:8010/docs/')
with sync_playwright() as p:
    browser=p.chromium.launch(executable_path=os.environ.get('PAGES_BROWSER_EXECUTABLE') or shutil.which('chromium'),headless=True,args=['--no-sandbox','--disable-dev-shm-usage'])
    page=browser.new_page(viewport={'width':1440,'height':1100},reduced_motion='reduce')
    page.set_default_timeout(10000)
    errors=[]
    failed=[]
    page.on('pageerror',lambda error:errors.append(str(error)))
    page.on('response',lambda response:failed.append((response.url,response.status)) if response.status>=400 else None)
    assert page.goto(BASE).status==200
    page.get_by_role('button',name='Entrar como solicitante').click()
    expect(page.get_by_role('heading',name='Visão geral',exact=False)).to_be_visible()
    page.get_by_role('link',name='Novo chamado',exact=False).first.click()
    page.locator('input[name=title]').fill('Teste navegável: computador da recepção')
    page.locator('select[name=category]').select_option(label='Hardware')
    page.locator('textarea[name=description]').fill('O computador de teste não liga. Registro fictício.')
    page.get_by_role('button',name='Registrar chamado',exact=False).click()
    expect(page.get_by_role('heading',name='Teste navegável: computador da recepção')).to_be_visible()
    expect(page.locator('.page-heading .badge')).to_have_text('Aberto')
    page.locator('#demo-role').select_option('tech')
    page.get_by_role('button',name='Assumir chamado').click()
    expect(page.locator('.page-heading .badge')).to_have_text('Em triagem')
    form=page.locator('form[data-action=update-ticket]')
    form.locator('[name=status]').select_option('in_progress')
    form.get_by_role('button',name='Salvar atendimento').click()
    comment=page.locator('form[data-action=comment]')
    comment.locator('[name=body]').fill('Nota técnica reservada de teste')
    comment.locator('[name=internal]').check()
    comment.get_by_role('button',name='Enviar mensagem').click()
    page.locator('#demo-role').select_option('requester')
    expect(page.get_by_text('Nota técnica reservada de teste',exact=True)).to_have_count(0)
    page.locator('#demo-role').select_option('tech')
    form=page.locator('form[data-action=update-ticket]')
    form.locator('[name=status]').select_option('resolved')
    form.locator('[name=resolution]').fill('Fonte substituída. Funcionamento validado no exemplo.')
    form.get_by_role('button',name='Salvar atendimento').click()
    page.locator('#demo-role').select_option('requester')
    page.get_by_role('button',name='Confirmar solução e encerrar').click()
    expect(page.locator('.page-heading .badge')).to_have_text('Encerrado')
    page.get_by_role('button',name='Reabrir chamado').click()
    expect(page.locator('.page-heading .badge')).to_have_text('Em triagem')
    page.reload()
    expect(page.get_by_role('heading',name='Teste navegável: computador da recepção')).to_be_visible()
    print('Ciclo do chamado, notas internas e persistência: OK')
    page.get_by_role('link',name='Central de ajuda',exact=True).click()
    page.locator('#help-search').fill('impressora')
    page.get_by_role('button',name='Buscar orientação').click()
    page.locator('.article-card').filter(has_text='O que verificar quando a impressora não imprime?').click()
    page.get_by_role('button',name='Sim, ajudou').click()
    expect(page.get_by_role('button',name='Sim, ajudou')).to_have_attribute('aria-pressed','true')
    page.get_by_role('link',name='Enviar dúvida sobre este artigo').click()
    expect(page.locator('input[name=title]')).to_have_value('Dúvida sobre: O que verificar quando a impressora não imprime?')
    page.locator('textarea[name=description]').fill('Como selecionar frente e verso?')
    page.get_by_role('button',name='Enviar dúvida',exact=False).click()
    expect(page.get_by_text('Orientação consultada:',exact=False)).to_be_visible()
    print('Busca, artigos, avaliação e dúvida com contexto: OK')
    page.locator('#demo-role').select_option('tech')
    page.goto(BASE+'#/artigos')
    page.get_by_role('link',name='Novo artigo').click()
    page.locator('input[name=title]').fill('Orientação de teste do site')
    page.locator('textarea[name=summary]').fill('Resumo de exemplo para validar rascunhos.')
    page.locator('textarea[name=body]').fill('Texto fictício para testar a publicação de orientações.')
    page.get_by_role('button',name='Salvar orientação').click()
    expect(page.get_by_text('Rascunho: visível apenas no perfil de técnico.',exact=True)).to_be_visible()
    page.locator('#demo-role').select_option('requester')
    expect(page.get_by_role('heading',name='Artigo não encontrado')).to_be_visible()
    page.locator('#demo-role').select_option('tech')
    page.get_by_role('link',name='Editar orientação',exact=True).click()
    page.locator('input[name=published]').check()
    page.get_by_role('button',name='Salvar orientação').click()
    expect(page.get_by_role('heading',name='Orientação de teste do site')).to_be_visible()
    page.locator('#demo-role').select_option('requester')
    expect(page.get_by_role('heading',name='Orientação de teste do site')).to_be_visible()
    print('Rascunho e publicação de artigos: OK')
    page.goto(BASE+'#/novo')
    page.locator('input[name=title]').fill('<script>window.__xss=true</script>')
    page.locator('select[name=category]').select_option(label='Software')
    page.locator('textarea[name=description]').fill('<img src=x onerror="window.__xss=true">')
    page.get_by_role('button',name='Registrar chamado',exact=False).click()
    expect(page.get_by_role('heading',name='<script>window.__xss=true</script>',exact=True)).to_be_visible()
    assert page.evaluate('Boolean(window.__xss)') is False
    print('Escape de HTML nos formulários: OK')
    for width in [1440,768,390]:
        page.set_viewport_size({'width':width,'height':1000})
        for route in ['#/','#/chamados','#/novo','#/ajuda','#/duvida','#/artigo/1']:
            page.goto(BASE+route)
            page.locator('#main-content').wait_for()
            assert page.evaluate('document.documentElement.scrollWidth <= innerWidth'),(width,route)
    assert not errors,errors
    assert not failed,failed
    browser.close()
    print('Desktop, tablet e celular; arquivos estáticos e JavaScript: OK')
